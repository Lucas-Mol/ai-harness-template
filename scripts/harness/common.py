"""Shared helpers for the harness scripts (sync, lint, gc, init)."""

from __future__ import annotations

import sys
from pathlib import Path
from typing import Any

try:
    import yaml
except ImportError:
    sys.exit("error: PyYAML is required. Run: make harness-deps")

ROOT = Path(__file__).resolve().parents[2]
CONFIG_PATH = ROOT / "harness.config.yaml"
AGENTS_DIR = ROOT / ".agents"
MANIFEST_PATH = AGENTS_DIR / ".generated.json"

GENERATED_MARKER = "GENERATED BY scripts/harness/sync — DO NOT EDIT"
KNOWN_TARGETS = ("claude", "copilot", "cursor", "codex", "gemini")
ABSTRACT_TOOLS = ("read", "write", "shell", "web")
MODEL_HINTS = ("fast", "balanced", "deep")


class HarnessError(Exception):
    """A problem in harness sources or configuration that the user must fix."""


def load_yaml(path: Path) -> Any:
    try:
        return yaml.safe_load(path.read_text(encoding="utf-8"))
    except yaml.YAMLError as exc:
        raise HarnessError(f"{rel(path)}: invalid YAML: {exc}") from exc


def load_config() -> dict[str, Any]:
    if not CONFIG_PATH.is_file():
        raise HarnessError(f"missing {rel(CONFIG_PATH)}")
    config = load_yaml(CONFIG_PATH)
    if not isinstance(config, dict):
        raise HarnessError(f"{rel(CONFIG_PATH)}: expected a mapping at top level")
    return config


def split_frontmatter(text: str, source: Path) -> tuple[dict[str, Any], str]:
    """Return (frontmatter, body). Raises HarnessError when frontmatter is missing or invalid."""
    if not text.startswith("---\n"):
        raise HarnessError(f"{rel(source)}: missing YAML frontmatter (file must start with '---')")
    end = text.find("\n---\n", 4)
    if end == -1:
        raise HarnessError(f"{rel(source)}: unterminated YAML frontmatter")
    try:
        meta = yaml.safe_load(text[4:end]) or {}
    except yaml.YAMLError as exc:
        raise HarnessError(f"{rel(source)}: invalid frontmatter: {exc}") from exc
    if not isinstance(meta, dict):
        raise HarnessError(f"{rel(source)}: frontmatter must be a mapping")
    return meta, text[end + len("\n---\n"):]


def dump_frontmatter(meta: dict[str, Any]) -> str:
    dumped = yaml.safe_dump(meta, sort_keys=False, allow_unicode=True, width=10_000)
    return f"---\n{dumped}---\n"


def rel(path: Path) -> str:
    try:
        return path.resolve().relative_to(ROOT).as_posix()
    except ValueError:
        return str(path)
