#!/usr/bin/env bash
# Blocks writes to protected paths (harness.config.yaml: protected_paths) and to generated adapter files.
# Usage: protect-paths.sh <path>...    Exit 0 = allowed, 2 = blocked (reason on stderr).
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
CONFIG="$ROOT/harness.config.yaml"
MANIFEST="$ROOT/.agents/.generated.json"
MARKER="GENERATED BY scripts/harness/sync"

read_patterns() {
  awk '
    /^protected_paths:/ { inlist = 1; next }
    inlist && /^[^[:space:]#]/ { inlist = 0 }
    inlist && /^[[:space:]]+-[[:space:]]+/ {
      sub(/^[[:space:]]+-[[:space:]]+/, "")
      sub(/[[:space:]]+#.*$/, "")
      gsub(/["\047]/, "")
      print
    }' "$CONFIG"
}

to_relative() {
  local path="${1#./}"
  case "$path" in
    "$ROOT"/*) path="${path#"$ROOT"/}" ;;
  esac
  printf '%s' "$path"
}

# Glob match: "*" spans "/"; patterns without "/" (or starting with "**/") also match the basename.
matches() {
  local path="$1" pattern="$2" base="${1##*/}"
  # shellcheck disable=SC2254
  case "$path" in $pattern) return 0 ;; esac
  if [[ "$pattern" == "**/"* ]]; then
    local tail="${pattern#\*\*/}"
    # shellcheck disable=SC2254
    case "$path" in $tail | */$tail) return 0 ;; esac
  elif [[ "$pattern" != */* ]]; then
    # shellcheck disable=SC2254
    case "$base" in $pattern) return 0 ;; esac
  fi
  return 1
}

is_generated() {
  local rel="$1"
  [[ -f "$MANIFEST" ]] && grep -qF "\"$rel\":" "$MANIFEST" && return 0
  [[ -f "$ROOT/$rel" ]] && head -n 5 "$ROOT/$rel" | grep -qF "$MARKER"
}

[[ -f "$CONFIG" ]] || { echo "protect-paths: missing $CONFIG" >&2; exit 1; }
mapfile -t patterns < <(read_patterns)

blocked=0
for arg in "$@"; do
  rel="$(to_relative "$arg")"
  for pattern in "${patterns[@]}"; do
    if matches "$rel" "$pattern"; then
      echo "BLOCKED: '$rel' is a protected path (pattern '$pattern' in harness.config.yaml). Ask a human to make this change." >&2
      blocked=1
      continue 2
    fi
  done
  if is_generated "$rel"; then
    echo "BLOCKED: '$rel' is generated by scripts/harness/sync. Edit its source (AGENTS.md or .agents/) and run 'make harness-sync'." >&2
    blocked=1
  fi
done

[[ "$blocked" -eq 0 ]] || exit 2
